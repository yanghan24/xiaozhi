#!/usr/bin/env python3
"""Extract the binding UI's missing glyphs from the existing PuHui C font.

No rasterization or network access is involved. The bitmap bytes and glyph
metrics are copied verbatim; only bitmap offsets and the Unicode map change.
"""

import argparse
import ast
import hashlib
from pathlib import Path
import re


FIELDS = ("bitmap_index", "adv_w", "box_w", "box_h", "ofs_x", "ofs_y")
TOKEN = re.compile(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[{}]', re.DOTALL)


def array_body(source: str, name: str) -> str:
    match = re.search(r'\b' + re.escape(name) + r'\[\]\s*=\s*\{(.*?)\n\};', source, re.DOTALL)
    if not match:
        raise ValueError(f"Missing array {name}")
    return match.group(1)


def read_font(path: Path) -> tuple[dict[int, tuple[dict[str, int], bytes]], str]:
    source = path.read_text(encoding="utf-8")
    for name, value in (("bpp", 4), ("bitmap_format", 0), ("line_height", 38), ("base_line", 9)):
        if not re.search(r'\.' + name + r'\s*=\s*' + str(value) + r'\b', source):
            raise ValueError(f"{path}: expected {name}={value}")
    bitmap = array_body(source, "glyph_bitmap")
    glyphs = array_body(source, "glyph_dsc")
    descriptors = []
    for entry in re.findall(r'\{([^{}]*)\}', glyphs):
        descriptor = {name: int(value) for name, value in re.findall(r'\.(\w+)\s*=\s*(-?\d+)', entry)}
        if set(descriptor) != set(FIELDS):
            raise ValueError(f"{path}: unexpected glyph descriptor")
        descriptors.append(descriptor)
    comments = list(re.finditer(r'/\* U\+([0-9A-Fa-f]+)\b.*?\*/', bitmap))
    if len(descriptors) != len(comments) + 1 or any(descriptors[0].values()):
        raise ValueError(f"{path}: bitmap comments and descriptor indices disagree")
    offset = 0
    result = {}
    for index, comment in enumerate(comments):
        codepoint = int(comment.group(1), 16)
        end = comments[index + 1].start() if index + 1 < len(comments) else len(bitmap)
        body = bitmap[comment.end():end]
        values = re.findall(r'0x[0-9A-Fa-f]+', body)
        if re.sub(r'0x[0-9A-Fa-f]+|[\s,]', '', body):
            raise ValueError(f"{path}: unexpected bitmap syntax at U+{codepoint:04X}")
        data = bytes(int(value, 16) for value in values)
        descriptor = descriptors[index + 1]
        expected_size = (descriptor["box_w"] * descriptor["box_h"] * 4 + 7) // 8
        if descriptor["bitmap_index"] != offset or len(data) != expected_size:
            raise ValueError(f"{path}: bitmap offsets or dimensions disagree at U+{codepoint:04X}")
        if codepoint in result:
            raise ValueError(f"{path}: duplicate U+{codepoint:04X}")
        result[codepoint] = (descriptor, data)
        offset += len(data)
    return result, hashlib.sha256(path.read_bytes()).hexdigest()


def binding_codepoints(path: Path) -> set[int]:
    source = path.read_text(encoding="utf-8")
    codepoints = set()
    for name in ("CreateDeviceBindingUi", "UpdateBindingCountdown", "ShowDeviceBinding"):
        start = re.search(r'\bLcdDisplay::' + name + r'\([^)]*\)\s*\{', source)
        if not start:
            raise ValueError(f"Missing binding function {name}")
        depth = 1
        for token in TOKEN.finditer(source, start.end()):
            text = token.group()
            if text == "{":
                depth += 1
            elif text == "}":
                depth -= 1
                if not depth:
                    break
            elif text.startswith('"'):
                codepoints.update(ord(char) for char in ast.literal_eval(text) if ord(char) > 127)
        if depth:
            raise ValueError(f"Unclosed binding function {name}")
    if not codepoints:
        raise ValueError("No binding UI text found")
    return codepoints


def generate(source_path: Path, basic_path: Path, lcd_path: Path) -> tuple[str, int, int]:
    full, full_hash = read_font(source_path)
    basic, basic_hash = read_font(basic_path)
    required = binding_codepoints(lcd_path)
    missing = sorted(required - basic.keys())
    if not missing:
        raise ValueError("The basic font already covers the binding UI")
    absent = set(missing) - full.keys()
    if absent:
        raise ValueError("Source font lacks: " + " ".join(f"U+{cp:04X}" for cp in sorted(absent)))
    if missing[-1] - missing[0] >= 65535 or len(missing) >= 65535:
        raise ValueError("Supplement no longer fits a single sparse Unicode map")
    lines = [
        "/* Generated by scripts/generate_binding_font.py; do not edit by hand.",
        " * Source: 78/xiaozhi-fonts 1.6.0, src/font_puhui_30_4.c.",
        " * Repository: https://github.com/78/xiaozhi-fonts",
        " * Upstream component declares license: MIT in idf_component.yml.",
        " * Original rasterization: PuHui, 30 px, 4 bpp, --no-compress --no-prefilter.",
        " * Glyph bitmap bytes and metrics are copied unchanged from that source.",
        f" * Source SHA-256: {full_hash}",
        f" * Basic SHA-256: {basic_hash}",
        " * Regenerate (from the firmware root):",
        " * python3 scripts/generate_binding_font.py \\",
        " *   --source managed_components/78__xiaozhi-fonts/src/font_puhui_30_4.c \\",
        " *   --lcd-source main/display/lcd_display.cc \\",
        " *   --output main/display/fonts/font_puhui_binding_30_4.c",
        " */", "", '#include "lvgl.h"', "",
        "LV_FONT_DECLARE(font_puhui_basic_30_4);", "",
        "static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {",
    ]
    offset = 0
    descriptors = [{field: 0 for field in FIELDS}]
    for cp in missing:
        descriptor, data = full[cp]
        if not any(data) or not descriptor["adv_w"]:
            raise ValueError(f"Source glyph U+{cp:04X} is empty")
        lines.append(f"    /* U+{cp:04X} {chr(cp)} */")
        lines.extend("    " + ", ".join(f"0x{value:02x}" for value in data[i:i + 16]) + ","
                     for i in range(0, len(data), 16))
        descriptors.append({**descriptor, "bitmap_index": offset})
        offset += len(data)
    lines.extend(["};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {"])
    lines.extend("    {" + ", ".join(f".{field} = {descriptor[field]}" for field in FIELDS) + "},"
                 for descriptor in descriptors)
    lines.extend(["};", "", "static const uint16_t unicode_list[] = {"])
    lines.extend("    " + ", ".join(f"0x{cp - missing[0]:04x}" for cp in missing[i:i + 10]) + ","
                 for i in range(0, len(missing), 10))
    lines.extend([
        "};", "", "static const lv_font_fmt_txt_cmap_t cmaps[] = {{",
        f"    .range_start = {missing[0]}, .range_length = {missing[-1] - missing[0] + 1},",
        "    .glyph_id_start = 1, .unicode_list = unicode_list, .glyph_id_ofs_list = NULL,",
        f"    .list_length = {len(missing)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,",
        "}};", "", "static const lv_font_fmt_txt_dsc_t font_dsc = {",
        "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,",
        "    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4,",
        "    .kern_classes = 0, .bitmap_format = 0,", "};", "",
        "const lv_font_t font_puhui_binding_30_4 = {",
        "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
        "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
        "    .line_height = 38, .base_line = 9, .subpx = LV_FONT_SUBPX_NONE,",
        "    .underline_position = -2, .underline_thickness = 2,",
        "    .dsc = &font_dsc, .fallback = &font_puhui_basic_30_4, .user_data = NULL,",
        "};", "",
    ])
    return "\n".join(lines), len(missing), offset


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--basic", type=Path, help="Defaults to font_puhui_basic_30_4.c beside source")
    parser.add_argument("--lcd-source", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--check", action="store_true", help="Verify the generated file without rewriting it")
    args = parser.parse_args()
    basic = args.basic or args.source.with_name("font_puhui_basic_30_4.c")
    output, count, bitmap_bytes = generate(args.source, basic, args.lcd_source)
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != output:
            parser.exit(1, f"Binding font is missing or stale: {args.output}\n")
        print(f"Verified {count} supplementary glyphs, {bitmap_bytes} bitmap bytes: {args.output}")
    else:
        args.output.write_text(output, encoding="utf-8")
        print(f"Generated {count} supplementary glyphs, {bitmap_bytes} bitmap bytes: {args.output}")


if __name__ == "__main__":
    main()
