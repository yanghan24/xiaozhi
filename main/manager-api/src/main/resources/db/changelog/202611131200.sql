CREATE TABLE dc_ota_firmware (
 firmware_id VARCHAR(32) PRIMARY KEY,
 github_release_id BIGINT NOT NULL,
 github_asset_id BIGINT NOT NULL UNIQUE,
 release_tag VARCHAR(255) NOT NULL,
 prerelease BOOLEAN NOT NULL,
 source_commit CHAR(40) NOT NULL,
 source_url VARCHAR(512) NOT NULL,
 manifest_sha256 CHAR(64) NOT NULL,
 sha256 CHAR(64) NOT NULL,
 elf_sha256 CHAR(64) NOT NULL,
 app_version VARCHAR(32) NOT NULL,
 board_type VARCHAR(128) NOT NULL,
 flash_size INT NOT NULL,
 min_revision INT NOT NULL,
 max_revision INT NOT NULL,
 partition_layout VARCHAR(128) NOT NULL,
 partition_table_sha256 CHAR(64) NOT NULL,
 app_partition_bytes INT NOT NULL,
 image_size INT NOT NULL,
 image LONGBLOB NOT NULL,
 verification_status VARCHAR(16) NOT NULL,
 operator_id BIGINT NOT NULL,
 created_at_ms BIGINT NOT NULL
);
