bool speaker_boot_brand_unpack(const speaker_boot_brand_asset_t* asset, uint8_t* output, size_t size) {
    const uint8_t* input = asset->packed;
    size_t remaining = asset->packed_size;
    while (remaining > 0) {
        const unsigned control = *input++;
        --remaining;
        if (control == 128) {
            continue;
        }
        const bool repeated = control > 128;
        const size_t count = repeated ? 257 - control : control + 1;
        const size_t consumed = repeated ? 1 : count;
        if (count > size || consumed > remaining) {
            return false;
        }
        if (repeated) {
            memset(output, *input, count);
        } else {
            memcpy(output, input, count);
        }
        output += count;
        size -= count;
        input += consumed;
        remaining -= consumed;
    }
    return size == 0;
}
